func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)
	if err := json.NewEncoder(w).Encode(v); err != nil {
		log.Printf("response encode failed: %v", err)
	}
}

func fail(w http.ResponseWriter, status int, message string) {
	writeJSON(w, status, map[string]string{"error": message})
}

func decode(w http.ResponseWriter, r *http.Request, dst any) error {
	r.Body = http.MaxBytesReader(w, r.Body, maxRequestBody)
	dec := json.NewDecoder(r.Body)
	dec.DisallowUnknownFields()
	if err := dec.Decode(dst); err != nil {
		return err
	}
	var extra any
	if err := dec.Decode(&extra); !errors.Is(err, io.EOF) {
		if err == nil {
			return errors.New("multiple JSON values")
		}
		return err
	}
	return nil
}

func randomHex(n int) (string, error) {
	buf := make([]byte, n)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return hex.EncodeToString(buf), nil
}

func newUUID() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	h := hex.EncodeToString(b)
	return h[:8] + "-" + h[8:12] + "-" + h[12:16] + "-" + h[16:20] + "-" + h[20:], nil
}

func validUUID(s string) bool {
	if len(s) != 36 || s[8] != '-' || s[13] != '-' || s[18] != '-' || s[23] != '-' {
		return false
	}
	_, err := hex.DecodeString(strings.ReplaceAll(s, "-", ""))
	return err == nil
}

func hashPassword(password string, pepper []byte) (string, error) {
	salt := make([]byte, 16)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	material := make([]byte, 0, len(password)+len(pepper))
	material = append(material, password...)
	material = append(material, pepper...)
	key := argon2.IDKey(material, salt, argonTime, argonMemoryKiB, argonThreads, argonKeyBytes)
	return fmt.Sprintf("$argon2id$v=19$m=%d,t=%d,p=%d$%s$%s", argonMemoryKiB, argonTime, argonThreads, hex.EncodeToString(salt), hex.EncodeToString(key)), nil
}

func verifyPassword(password string, pepper []byte, encoded string) bool {
	parts := strings.Split(encoded, "$")
	if len(parts) != 6 || parts[1] != "argon2id" || parts[2] != "v=19" {
		return false
	}
	// Accept only the cost policy generated by this application. This also
	// prevents a malformed database verifier from requesting unbounded RAM/CPU.
	if parts[3] != fmt.Sprintf("m=%d,t=%d,p=%d", argonMemoryKiB, argonTime, argonThreads) {
		return false
	}
	salt, err := hex.DecodeString(parts[4])
	if err != nil || len(salt) != 16 {
		return false
	}
	want, err := hex.DecodeString(parts[5])
	if err != nil || len(want) != argonKeyBytes {
		return false
	}
	material := make([]byte, 0, len(password)+len(pepper))
	material = append(material, password...)
	material = append(material, pepper...)
	got := argon2.IDKey(material, salt, argonTime, argonMemoryKiB, argonThreads, argonKeyBytes)
	return subtle.ConstantTimeCompare(got, want) == 1
}

func clientIP(r *http.Request) string {
	host, _, err := net.SplitHostPort(r.RemoteAddr)
	if err == nil {
		return host
	}
	return r.RemoteAddr
}

func withRequestID(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		id := strings.TrimSpace(r.Header.Get("X-Request-ID"))
		if !validUUID(id) {
			var err error
			id, err = newUUID()
			if err != nil {
				log.Printf("request id generation failed: %v", err)
				fail(w, http.StatusInternalServerError, "internal error")
				return
			}
		}
		r.Header.Set("X-Request-ID", id)
		w.Header().Set("X-Request-ID", id)
		next.ServeHTTP(w, r)
	})
}

func withSecurityHeaders(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("X-Content-Type-Options", "nosniff")
		w.Header().Set("X-Frame-Options", "DENY")
		w.Header().Set("Referrer-Policy", "no-referrer")
		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Content-Security-Policy", "default-src 'self'; script-src 'self'; style-src 'self'; object-src 'none'; frame-ancestors 'none'; base-uri 'self'")
		next.ServeHTTP(w, r)
	})
}

func (a *App) audit(ctx context.Context, p *Principal, eventType, entityType, entityRef, outcome string, r *http.Request, details map[string]any) {
	var actor any
	if p != nil && p.ID != "" {
		actor = p.ID
	}
	payload, err := json.Marshal(details)
	if err != nil {
		payload = []byte(`{}`)
	}
	_, err = a.db.Exec(ctx, `INSERT INTO audit_events(actor_user_id,event_type,entity_type,entity_ref,outcome,request_id,source_ip,details)
		VALUES($1::uuid,$2,$3,NULLIF($4,''),$5,NULLIF($6,'')::uuid,NULLIF($7,'')::inet,$8::jsonb)`, actor, eventType, entityType, entityRef, outcome, r.Header.Get("X-Request-ID"), clientIP(r), string(payload))
	if err != nil {
		log.Printf("audit insert failed event=%s request_id=%s: %v", eventType, r.Header.Get("X-Request-ID"), err)
	}
}

// rateLimit uses a Redis counter with a fixed window. Redis failure is fail-closed:
// the system does not silently turn off its declared brute-force/rate controls.
func (a *App) rateLimit(w http.ResponseWriter, r *http.Request, key string, max int64, window time.Duration) bool {
	ctx := r.Context()
	value, err := a.rdb.Eval(ctx, `local n=redis.call('INCR',KEYS[1]); if n==1 then redis.call('EXPIRE',KEYS[1],ARGV[1]); end; return n`, []string{"rate:" + key}, int(window.Seconds())).Int64()
	if err != nil {
		log.Printf("rate limit service unavailable: %v", err)
		fail(w, http.StatusServiceUnavailable, "rate limit service unavailable")
		return false
	}
	if value > max {
		ttl, err := a.rdb.TTL(ctx, "rate:"+key).Result()
		if err == nil && ttl > 0 {
			w.Header().Set("Retry-After", strconv.Itoa(maxInt(1, int(ttl.Seconds()))))
		}
		fail(w, http.StatusTooManyRequests, "rate limit exceeded")
		return false
	}
	return true
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

func (a *App) auth(next func(http.ResponseWriter, *http.Request, *Principal)) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		header := r.Header.Get("Authorization")
		if !strings.HasPrefix(header, "Bearer ") {
			fail(w, http.StatusUnauthorized, "authentication required")
			return
		}
		token := strings.TrimSpace(strings.TrimPrefix(header, "Bearer "))
		if token == "" || strings.ContainsAny(token, " \t\r\n") {
			fail(w, http.StatusUnauthorized, "invalid or expired session")
			return
		}
		raw, err := a.rdb.Get(r.Context(), "session:"+token).Result()
		if err != nil {
			fail(w, http.StatusUnauthorized, "invalid or expired session")
			return
		}
		var p Principal
		if err := json.Unmarshal([]byte(raw), &p); err != nil || p.ID == "" || p.Role == "" {
			fail(w, http.StatusUnauthorized, "invalid session")
			return
		}
		next(w, r, &p)
	}
}

func (a *App) admin(next func(http.ResponseWriter, *http.Request, *Principal)) http.HandlerFunc {
	return a.auth(func(w http.ResponseWriter, r *http.Request, p *Principal) {
		if p.Role != "ADMIN" {
			a.audit(r.Context(), p, "privileged_access_denied", "operation", r.URL.Path, "denied", r, nil)
			fail(w, http.StatusForbidden, "insufficient privileges")
			return
		}
		next(w, r, p)
	})
}

func (a *App) login(w http.ResponseWriter, r *http.Request) {
	if !a.rateLimit(w, r, "login-ip:"+clientIP(r), 10, time.Minute) {
		return
	}
	var in struct {
		UniversityID string `json:"university_id"`
		Password     string `json:"password"`
	}
	if decode(w, r, &in) != nil || strings.TrimSpace(in.UniversityID) == "" || in.Password == "" || len(in.Password) > 1024 {
		fail(w, http.StatusBadRequest, "invalid request")
		return
	}
	var p Principal
	var verifier string
	var active bool
	err := a.db.QueryRow(r.Context(), `SELECT u.user_id::text,u.full_name,COALESCE(u.service_unit_code,''),u.password_hash,u.is_active,rr.code
		FROM users u JOIN user_roles ur ON ur.user_id=u.user_id JOIN roles rr ON rr.role_id=ur.role_id
		WHERE u.university_id=$1 ORDER BY CASE rr.code WHEN 'ADMIN' THEN 0 WHEN 'USER' THEN 1 ELSE 2 END LIMIT 1`, strings.TrimSpace(in.UniversityID)).Scan(&p.ID, &p.Name, &p.Unit, &verifier, &active, &p.Role)
	if err != nil && !errors.Is(err, pgx.ErrNoRows) {
		log.Printf("login database query failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	if errors.Is(err, pgx.ErrNoRows) || !active {
		// Spend the same password-verification cost for an unknown login so the
		// obvious timing difference does not reveal whether the account exists.
		_ = verifyPassword(in.Password, a.pepper, a.dummyHash)
		fail(w, http.StatusUnauthorized, "invalid credentials")
		return
	}
	if !verifyPassword(in.Password, a.pepper, verifier) {
		a.audit(r.Context(), nil, "login_failed", "user", strings.TrimSpace(in.UniversityID), "denied", r, nil)
		fail(w, http.StatusUnauthorized, "invalid credentials")
		return
	}
	token, err := randomHex(32)
	if err != nil {
		log.Printf("token generation failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	session, _ := json.Marshal(p)
	if err := a.rdb.Set(r.Context(), "session:"+token, session, a.ttl).Err(); err != nil {
		fail(w, http.StatusServiceUnavailable, "session service unavailable")
		return
	}
	if err := a.rdb.SAdd(r.Context(), "sessions:user:"+p.ID, token).Err(); err != nil {
		_ = a.rdb.Del(r.Context(), "session:"+token).Err()
		fail(w, http.StatusServiceUnavailable, "session service unavailable")
		return
	}
	_ = a.rdb.Expire(r.Context(), "sessions:user:"+p.ID, a.ttl).Err()
	a.audit(r.Context(), &p, "login", "user", p.ID, "success", r, nil)
	writeJSON(w, http.StatusOK, map[string]any{"access_token": token, "token_type": "Bearer", "expires_in": int(a.ttl.Seconds()), "user": p})
}

func (a *App) logout(w http.ResponseWriter, r *http.Request, p *Principal) {
	token := strings.TrimSpace(strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer "))
	if err := a.rdb.Del(r.Context(), "session:"+token).Err(); err != nil {
		fail(w, http.StatusServiceUnavailable, "session service unavailable")
		return
	}
	_ = a.rdb.SRem(r.Context(), "sessions:user:"+p.ID, token).Err()
	a.audit(r.Context(), p, "logout", "user", p.ID, "success", r, nil)
	writeJSON(w, http.StatusOK, map[string]string{"status": "logged_out"})
}

func (a *App) getDocumentType(ctx context.Context, code string) (documentType, error) {
	key := "cache:document-type:" + code
	if raw, err := a.rdb.Get(ctx, key).Bytes(); err == nil {
		var cached documentType
		if json.Unmarshal(raw, &cached) == nil {
			return cached, nil
		}
	}
	var v documentType
	if err := a.db.QueryRow(ctx, `SELECT document_type_id,code,active FROM document_types WHERE code=$1`, code).Scan(&v.ID, &v.Code, &v.Active); err != nil {
		return documentType{}, err
	}
	if b, err := json.Marshal(v); err == nil {
		_ = a.rdb.Set(ctx, key, b, 5*time.Minute).Err()
	}
	return v, nil
}

func (a *App) createApplication(w http.ResponseWriter, r *http.Request, p *Principal) {
	if p.Role != "USER" {
		fail(w, http.StatusForbidden, "operation not permitted")
		return
	}
	if !a.rateLimit(w, r, "create-minute:"+p.ID, 5, time.Minute) || !a.rateLimit(w, r, "create-hour:"+p.ID, 30, time.Hour) {
		return
	}
	var in struct {
		TypeCode string `json:"document_type_code"`
		Comment  string `json:"comment"`
	}
	if decode(w, r, &in) != nil || strings.TrimSpace(in.TypeCode) == "" || len([]rune(in.Comment)) > 2000 {
		fail(w, http.StatusBadRequest, "invalid request")
		return
	}
	in.TypeCode = strings.TrimSpace(in.TypeCode)
	in.Comment = strings.TrimSpace(in.Comment)
	idempotencyKey := strings.TrimSpace(r.Header.Get("Idempotency-Key"))
	if idempotencyKey != "" && (len(idempotencyKey) < 8 || len(idempotencyKey) > 128 || strings.ContainsAny(idempotencyKey, "\r\n")) {
		fail(w, http.StatusBadRequest, "Idempotency-Key must be 8..128 characters")
		return
	}
	// The request fingerprint makes reuse of the same key with a different
	// payload a conflict, instead of accidentally replaying another operation.
	payloadBytes, err := json.Marshal(struct {
		DocumentTypeCode string `json:"document_type_code"`
		Comment          string `json:"comment"`
	}{DocumentTypeCode: in.TypeCode, Comment: in.Comment})
	if err != nil {
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	payloadSum := sha256.Sum256(payloadBytes)
	idempotencyPayloadHash := hex.EncodeToString(payloadSum[:])
	if idempotencyKey == "" {
		// The key and its fingerprint are either both NULL or both present.
		idempotencyPayloadHash = ""
	}
	typ, err := a.getDocumentType(r.Context(), in.TypeCode)
	if err != nil || !typ.Active {
		fail(w, http.StatusUnprocessableEntity, "document type unavailable")
		return
	}
	id, err := newUUID()
	if err != nil {
		log.Printf("application id generation failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	tx, err := a.db.Begin(r.Context())
	if err != nil {
		log.Printf("begin create application failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	defer tx.Rollback(r.Context())
	var created time.Time
	err = tx.QueryRow(r.Context(), `INSERT INTO applications(application_id,owner_user_id,service_unit_code,document_type_id,comment,idempotency_key,idempotency_payload_hash)
    	VALUES($1::uuid,$2::uuid,$3,$4,NULLIF($5::text,''),NULLIF($6::text,''),NULLIF($7::text,''))
    	ON CONFLICT (owner_user_id,idempotency_key) DO NOTHING RETURNING created_at`, id, p.ID, defaultUnit(p.Unit), typ.ID, in.Comment, idempotencyKey, idempotencyPayloadHash).Scan(&created)
	if errors.Is(err, pgx.ErrNoRows) && idempotencyKey != "" {
		var existingID, existingStatus, existingTypeCode, existingHash string
		var existingCreated time.Time
		err = tx.QueryRow(r.Context(), `SELECT a.application_id::text,a.status,a.created_at,dt.code,a.idempotency_payload_hash
			FROM applications a JOIN document_types dt USING(document_type_id)
			WHERE a.owner_user_id=$1::uuid AND a.idempotency_key=$2`, p.ID, idempotencyKey).Scan(&existingID, &existingStatus, &existingCreated, &existingTypeCode, &existingHash)
		if err != nil {
			log.Printf("idempotency lookup failed request_id=%s: %v", r.Header.Get("X-Request-ID"), err)
			fail(w, http.StatusInternalServerError, "internal error")
			return
		}
		if existingHash != idempotencyPayloadHash {
			fail(w, http.StatusConflict, "Idempotency-Key was already used with a different request")
			return
		}
		if err := tx.Commit(r.Context()); err != nil {
			log.Printf("idempotent replay transaction completion failed: %v", err)
			fail(w, http.StatusInternalServerError, "internal error")
			return
		}
		w.Header().Set("Idempotency-Replayed", "true")
		a.audit(r.Context(), p, "application_create_replayed", "application", existingID, "success", r, map[string]any{"idempotency_key": idempotencyKey})
		writeJSON(w, http.StatusCreated, map[string]any{"application_id": existingID, "status": existingStatus, "created_at": existingCreated, "document_type_code": existingTypeCode})
		return
	}
	if err == nil {
		_, err = tx.Exec(r.Context(), `INSERT INTO audit_events(actor_user_id,event_type,entity_type,entity_ref,outcome,request_id,source_ip,details)
			VALUES($1::uuid,'application_created','application',$2,'success',$3::uuid,$4::inet,jsonb_build_object('document_type_code',$5::text,'idempotency_key',$6::text))`, p.ID, id, r.Header.Get("X-Request-ID"), clientIP(r), typ.Code, idempotencyKey)
	}
	if err != nil {
		log.Printf("create application transaction failed request_id=%s: %v", r.Header.Get("X-Request-ID"), err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	if err := tx.Commit(r.Context()); err != nil {
		log.Printf("create application commit failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	writeJSON(w, http.StatusCreated, map[string]any{"application_id": id, "status": "submitted", "created_at": created, "document_type_code": typ.Code})
}

func defaultUnit(unit string) string {
	if strings.TrimSpace(unit) == "" {
		return "STUDENT"
	}
	return unit
}

func (a *App) application(w http.ResponseWriter, r *http.Request, p *Principal) {
	if p.Role != "USER" && p.Role != "ADMIN" {
		fail(w, http.StatusForbidden, "operation not permitted")
		return
	}
	if !a.rateLimit(w, r, "application-get:"+p.ID, 100, time.Minute) {
		return
	}
	id := r.PathValue("application_id")
	if !validUUID(id) {
		fail(w, http.StatusNotFound, "application not found")
		return
	}
	var typeCode, status, comment, unit string
	var created, updated time.Time
	query := `SELECT a.service_unit_code,dt.code,a.status,COALESCE(a.comment,''),a.created_at,a.updated_at
		FROM applications a JOIN document_types dt USING(document_type_id) WHERE a.application_id=$1::uuid`
	args := []any{id}
	if p.Role == "USER" {
		// Scope is applied in SQL so another user's row is never materialized by this query.
		query += ` AND a.owner_user_id=$2::uuid`
		args = append(args, p.ID)
	} else {
		query += ` AND a.service_unit_code=$2`
		args = append(args, p.Unit)
	}
	err := a.db.QueryRow(r.Context(), query, args...).Scan(&unit, &typeCode, &status, &comment, &created, &updated)
	if errors.Is(err, pgx.ErrNoRows) {
		a.audit(r.Context(), p, "application_read_denied", "application", id, "denied", r, nil)
		if p.Role == "ADMIN" {
			var exists bool
			if existsErr := a.db.QueryRow(r.Context(), `SELECT EXISTS(SELECT 1 FROM applications WHERE application_id=$1::uuid)`, id).Scan(&exists); existsErr != nil {
				log.Printf("application existence check failed request_id=%s: %v", r.Header.Get("X-Request-ID"), existsErr)
				fail(w, http.StatusInternalServerError, "internal error")
				return
			}
			if exists {
				fail(w, http.StatusForbidden, "application outside service scope")
				return
			}
		}
		fail(w, http.StatusNotFound, "application not found")
		return
	}
	if err != nil {
		log.Printf("read application failed request_id=%s: %v", r.Header.Get("X-Request-ID"), err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	a.audit(r.Context(), p, "application_read", "application", id, "success", r, nil)
	var commentValue any = comment
	if comment == "" {
		commentValue = nil
	}
	writeJSON(w, http.StatusOK, map[string]any{"application_id": id, "document_type_code": typeCode, "status": status, "comment": commentValue, "created_at": created, "updated_at": updated, "service_unit_code": unit})
}

func (a *App) listApplications(w http.ResponseWriter, r *http.Request, p *Principal) {
	if p.Role != "USER" && p.Role != "ADMIN" {
		fail(w, http.StatusForbidden, "operation not permitted")
		return
	}
	maxRequests := int64(60)
	if !a.rateLimit(w, r, "list:"+p.ID, maxRequests, time.Minute) {
		return
	}
	q := r.URL.Query()
	status := q.Get("status")
	allowedStatuses := map[string]bool{"": true, "submitted": true, "in_review": true, "approved": true, "rejected": true, "issued": true, "cancelled": true}
	if !allowedStatuses[status] {
		fail(w, http.StatusBadRequest, "invalid status filter")
		return
	}
	typeCode := strings.TrimSpace(q.Get("document_type_code"))
	page, pageSize := 1, 20
	var err error
	if q.Get("page") != "" {
		page, err = strconv.Atoi(q.Get("page"))
		if err != nil || page < 1 {
			fail(w, http.StatusBadRequest, "page must be >= 1")
			return
		}
	}
	if q.Get("page_size") != "" {
		pageSize, err = strconv.Atoi(q.Get("page_size"))
		if err != nil || pageSize < 1 || pageSize > 100 {
			fail(w, http.StatusBadRequest, "page_size must be 1..100")
			return
		}
	}
	var from, to any
	var fromTime, toTime time.Time
	if q.Get("created_from") != "" {
		fromTime, err = time.Parse(time.RFC3339, q.Get("created_from"))
		if err != nil {
			fail(w, http.StatusBadRequest, "created_from must be RFC3339 datetime")
			return
		}
		from = fromTime
	}
	if q.Get("created_to") != "" {
		toTime, err = time.Parse(time.RFC3339, q.Get("created_to"))
		if err != nil {
			fail(w, http.StatusBadRequest, "created_to must be RFC3339 datetime")
			return
		}
		to = toTime
	}
	if from != nil && to != nil {
		if toTime.Before(fromTime) || toTime.Sub(fromTime) > 366*24*time.Hour {
			fail(w, http.StatusBadRequest, "invalid date range (maximum 1 year)")
			return
		}
	} else if from != nil {
		if fromTime.After(time.Now().Add(time.Minute)) || time.Since(fromTime) > 366*24*time.Hour {
			fail(w, http.StatusBadRequest, "created_from must be within the last year")
			return
		}
	} else if to != nil {
		if toTime.Before(time.Now().Add(-366*24*time.Hour)) || toTime.After(time.Now().Add(time.Minute)) {
			fail(w, http.StatusBadRequest, "created_to must be within the last year")
			return
		}
	}
	baseWhere := `($1='' OR a.status=$1) AND ($2='' OR dt.code=$2) AND ($3::timestamptz IS NULL OR a.created_at >= $3::timestamptz) AND ($4::timestamptz IS NULL OR a.created_at <= $4::timestamptz) AND (($5='USER' AND a.owner_user_id=$6::uuid) OR ($5='ADMIN' AND a.service_unit_code=$7))`
	var total int64
	countSQL := `SELECT count(*) FROM applications a JOIN document_types dt USING(document_type_id) WHERE ` + baseWhere
	if err := a.db.QueryRow(r.Context(), countSQL, status, typeCode, from, to, p.Role, p.ID, p.Unit).Scan(&total); err != nil {
		log.Printf("application count failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	offset := (page - 1) * pageSize
	rows, err := a.db.Query(r.Context(), `SELECT a.application_id::text,dt.code,a.status,COALESCE(a.comment,''),a.created_at
		FROM applications a JOIN document_types dt USING(document_type_id) WHERE `+baseWhere+` ORDER BY a.created_at DESC LIMIT $8 OFFSET $9`, status, typeCode, from, to, p.Role, p.ID, p.Unit, pageSize, offset)
	if err != nil {
		log.Printf("list applications failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	defer rows.Close()
	items := make([]map[string]any, 0)
	for rows.Next() {
		var id, code, st, comment string
		var created time.Time
		if err := rows.Scan(&id, &code, &st, &comment, &created); err != nil {
			log.Printf("scan applications failed: %v", err)
			fail(w, http.StatusInternalServerError, "internal error")
			return
		}
		var commentValue any = comment
		if comment == "" {
			commentValue = nil
		}
		items = append(items, map[string]any{"application_id": id, "document_type_code": code, "status": st, "comment": commentValue, "created_at": created})
	}
	if err := rows.Err(); err != nil {
		log.Printf("iterate applications failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	a.audit(r.Context(), p, "application_list", "application", "", "success", r, map[string]any{"status": status, "document_type_code": typeCode, "page": page, "page_size": pageSize})
	writeJSON(w, http.StatusOK, map[string]any{"items": items, "page": page, "page_size": pageSize, "total": total})
}

func (a *App) changeStatus(w http.ResponseWriter, r *http.Request, p *Principal) {
	if !a.rateLimit(w, r, "status-change:"+p.ID, 20, time.Minute) {
		return
	}
	var in struct {
		Status string `json:"status"`
		Reason string `json:"reason"`
	}
	if decode(w, r, &in) != nil || len([]rune(in.Reason)) > 2000 {
		fail(w, http.StatusBadRequest, "invalid request")
		return
	}
	if in.Status != "submitted" && in.Status != "in_review" && in.Status != "approved" && in.Status != "rejected" && in.Status != "cancelled" {
		fail(w, http.StatusBadRequest, "invalid target status")
		return
	}
	id := r.PathValue("application_id")
	tx, err := a.db.Begin(r.Context())
	if err != nil {
		log.Printf("begin status transaction failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	defer tx.Rollback(r.Context())
	var old, unit string
	var updated time.Time
	if !validUUID(id) {
		fail(w, http.StatusNotFound, "application not found")
		return
	}
	err = tx.QueryRow(r.Context(), `SELECT status,service_unit_code,updated_at FROM applications WHERE application_id=$1::uuid FOR UPDATE`, id).Scan(&old, &unit, &updated)
	if errors.Is(err, pgx.ErrNoRows) {
		fail(w, http.StatusNotFound, "application not found")
		return
	}
	if err != nil {
		log.Printf("status target query failed request_id=%s: %v", r.Header.Get("X-Request-ID"), err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	if unit != p.Unit {
		a.audit(r.Context(), p, "status_change_denied", "application", id, "denied", r, nil)
		fail(w, http.StatusForbidden, "application outside service scope")
		return
	}
	allowed := map[string][]string{"submitted": {"in_review", "cancelled"}, "in_review": {"approved", "rejected", "cancelled"}, "approved": {"cancelled"}, "rejected": {"in_review"}}
	if old == in.Status {
		if err := tx.Commit(r.Context()); err != nil {
			fail(w, http.StatusInternalServerError, "internal error")
			return
		}
		writeJSON(w, http.StatusOK, map[string]any{"application_id": id, "old_status": old, "status": old, "changed_at": updated, "changed_by": p.ID})
		return
	}
	if (in.Status == "rejected" || in.Status == "cancelled") && strings.TrimSpace(in.Reason) == "" {
		fail(w, http.StatusBadRequest, "reason is required for rejected/cancelled status")
		return
	}
	ok := false
	for _, next := range allowed[old] {
		if next == in.Status {
			ok = true
			break
		}
	}
	if !ok {
		fail(w, http.StatusBadRequest, "invalid status transition")
		return
	}
	if err := tx.QueryRow(r.Context(), `UPDATE applications SET status=$1,updated_at=now() WHERE application_id=$2::uuid RETURNING updated_at`, in.Status, id).Scan(&updated); err != nil {
		log.Printf("update status failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	_, err = tx.Exec(r.Context(), `INSERT INTO application_status_history(application_id,changed_by_user_id,old_status,new_status,reason,request_id) VALUES($1::uuid,$2::uuid,$3,$4,NULLIF($5,''),$6::uuid)`, id, p.ID, old, in.Status, strings.TrimSpace(in.Reason), r.Header.Get("X-Request-ID"))
	if err == nil {
		reasonDigest := sha256.Sum256([]byte(strings.TrimSpace(in.Reason)))
		_, err = tx.Exec(r.Context(), `INSERT INTO audit_events(actor_user_id,event_type,entity_type,entity_ref,outcome,request_id,source_ip,details)
			VALUES($1::uuid,'application_status_changed','application',$2,'success',$3::uuid,$4::inet,jsonb_build_object('from',$5,'to',$6,'reason_sha256',$7))`, p.ID, id, r.Header.Get("X-Request-ID"), clientIP(r), old, in.Status, hex.EncodeToString(reasonDigest[:]))
	}
	if err == nil {
		var outboxID string
		outboxID, err = newUUID()
		if err == nil {
			_, err = tx.Exec(r.Context(), `INSERT INTO outbox_events(outbox_event_id,aggregate_type,aggregate_id,event_type,payload) VALUES($1::uuid,'application',$2::uuid,'status_changed',jsonb_build_object('application_id',$2,'actor_user_id',$3,'status',$4))`, outboxID, id, p.ID, in.Status)
		}
	}
	if err != nil {
		log.Printf("status transaction write failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	if err := tx.Commit(r.Context()); err != nil {
		log.Printf("status transaction commit failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"application_id": id, "old_status": old, "status": in.Status, "changed_at": updated, "changed_by": p.ID})
}

func (a *App) issue(w http.ResponseWriter, r *http.Request, p *Principal) {
	if !a.rateLimit(w, r, "document-issue:"+p.ID, 5, time.Minute) {
		return
	}
	var in struct {
		DocumentTitle string `json:"document_title"`
	}
	if decode(w, r, &in) != nil {
		fail(w, http.StatusBadRequest, "invalid request")
		return
	}
	in.DocumentTitle = strings.Join(strings.Fields(in.DocumentTitle), " ")
	if in.DocumentTitle == "" || len([]rune(in.DocumentTitle)) > 240 {
		fail(w, http.StatusUnprocessableEntity, "document_title is required and must be <= 240 characters")
		return
	}
	id := r.PathValue("application_id")
	ctx := r.Context()
	tx, err := a.db.Begin(ctx)
	if err != nil {
		log.Printf("begin issue transaction failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	defer tx.Rollback(ctx)
	var owner, unit, status string
	var docTypeTitle string
	if !validUUID(id) {
		fail(w, http.StatusNotFound, "application not found")
		return
	}
	err = tx.QueryRow(ctx, `SELECT a.owner_user_id::text,a.service_unit_code,a.status,dt.name FROM applications a JOIN document_types dt USING(document_type_id) WHERE a.application_id=$1::uuid FOR UPDATE OF a`, id).Scan(&owner, &unit, &status, &docTypeTitle)
	if errors.Is(err, pgx.ErrNoRows) {
		fail(w, http.StatusNotFound, "application not found")
		return
	}
	if err != nil {
		log.Printf("issue target query failed request_id=%s: %v", r.Header.Get("X-Request-ID"), err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	if unit != p.Unit {
		a.audit(ctx, p, "document_issue_denied", "application", id, "denied", r, nil)
		fail(w, http.StatusForbidden, "application outside service scope")
		return
	}
	if status == "issued" {
		fail(w, http.StatusConflict, "document already issued")
		return
	}
	if status != "approved" {
		fail(w, http.StatusBadRequest, "application must be approved before issue")
		return
	}
	var documentID, number string
	var createdAt time.Time
	documentID, err = newUUID()
	if err != nil {
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	randomNumber, err := randomHex(8)
	if err != nil {
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	number = "DOC-" + strings.ToUpper(randomNumber)
	issuedAt := time.Now().UTC()
	content := []byte(fmt.Sprintf("Учебный документ\nТип: %s\nНазвание: %s\nЗаявка: %s\nВладелец: %s\nНомер: %s\nВыдано: %s\n", docTypeTitle, in.DocumentTitle, id, owner, number, issuedAt.Format(time.RFC3339)))
	if len(content) > 5*1024*1024 {
		fail(w, http.StatusUnprocessableEntity, "document content exceeds limit")
		return
	}
	contentSum := sha256.Sum256(content)
	contentHash := hex.EncodeToString(contentSum[:])
	_, err = tx.Exec(ctx, `INSERT INTO documents(document_id,application_id,owner_user_id,document_number,document_title,mime_type,document_content,content_hash_sha256,issued_by_user_id,issued_at)
		VALUES($1::uuid,$2::uuid,$3::uuid,$4,$5,'text/plain',$6,$7,$8::uuid,$9)`, documentID, id, owner, number, in.DocumentTitle, content, contentHash, p.ID, issuedAt)
	if err == nil {
		err = tx.QueryRow(ctx, `UPDATE applications SET status='issued',updated_at=now() WHERE application_id=$1::uuid RETURNING updated_at`, id).Scan(&createdAt)
	}
	if err == nil {
		_, err = tx.Exec(ctx, `INSERT INTO application_status_history(application_id,changed_by_user_id,old_status,new_status,reason,request_id) VALUES($1::uuid,$2::uuid,'approved','issued','document issued',$3::uuid)`, id, p.ID, r.Header.Get("X-Request-ID"))
	}
	if err == nil {
		_, err = tx.Exec(ctx, `INSERT INTO document_issue_events(document_id,application_id,actor_user_id,document_hash_sha256,request_id) VALUES($1::uuid,$2::uuid,$3::uuid,$4,$5::uuid)`, documentID, id, p.ID, contentHash, r.Header.Get("X-Request-ID"))
	}
	if err == nil {
		_, err = tx.Exec(ctx, `INSERT INTO audit_events(actor_user_id,event_type,entity_type,entity_ref,outcome,request_id,source_ip,details) VALUES($1::uuid,'document_issued','document',$2,'success',$3::uuid,$4::inet,jsonb_build_object('application_id',$5,'document_number',$6,'sha256',$7))`, p.ID, documentID, r.Header.Get("X-Request-ID"), clientIP(r), id, number, contentHash)
	}
	if err == nil {
		var outboxID string
		outboxID, err = newUUID()
		if err == nil {
			_, err = tx.Exec(ctx, `INSERT INTO outbox_events(outbox_event_id,aggregate_type,aggregate_id,event_type,payload) VALUES($1::uuid,'document',$2::uuid,'document_ready',jsonb_build_object('application_id',$3,'document_id',$2,'owner_user_id',$4,'document_number',$5))`, outboxID, documentID, id, owner, number)
		}
	}
	if err != nil {
		log.Printf("issue transaction failed request_id=%s: %v", r.Header.Get("X-Request-ID"), err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	if err := tx.Commit(ctx); err != nil {
		log.Printf("issue transaction commit failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	// The issue fact is committed independently of notification processing.
	writeJSON(w, http.StatusCreated, map[string]any{"document_id": documentID, "document_number": number, "application_id": id, "status": "issued", "issued_at": issuedAt, "content_hash_sha256": contentHash})
}

func (a *App) getDocument(w http.ResponseWriter, r *http.Request, p *Principal) {
	if p.Role != "USER" && p.Role != "ADMIN" {
		fail(w, http.StatusForbidden, "operation not permitted")
		return
	}
	if !a.rateLimit(w, r, "document-get:"+p.ID, 100, time.Minute) {
		return
	}
	id := r.PathValue("document_id")
	if !validUUID(id) {
		fail(w, http.StatusNotFound, "document not found")
		return
	}
	var appID, number, title, mimeType, hash, status string
	var content []byte
	var issued time.Time
	query := `SELECT d.application_id::text,d.document_number,d.document_title,d.mime_type,d.document_content,d.content_hash_sha256,d.status,d.issued_at
		FROM documents d`
	args := []any{id}
	if p.Role == "USER" {
		// Fetch the document bytes only if the authenticated subject is its owner.
		query += ` WHERE d.document_id=$1::uuid AND d.owner_user_id=$2::uuid`
		args = append(args, p.ID)
	} else {
		query += ` JOIN applications a ON a.application_id=d.application_id WHERE d.document_id=$1::uuid AND a.service_unit_code=$2`
		args = append(args, p.Unit)
	}
	err := a.db.QueryRow(r.Context(), query, args...).Scan(&appID, &number, &title, &mimeType, &content, &hash, &status, &issued)
	if errors.Is(err, pgx.ErrNoRows) {
		a.audit(r.Context(), p, "document_read_denied", "document", id, "denied", r, nil)
		if p.Role == "ADMIN" {
			var exists bool
			if existsErr := a.db.QueryRow(r.Context(), `SELECT EXISTS(SELECT 1 FROM documents WHERE document_id=$1::uuid)`, id).Scan(&exists); existsErr != nil {
				log.Printf("document existence check failed request_id=%s: %v", r.Header.Get("X-Request-ID"), existsErr)
				fail(w, http.StatusInternalServerError, "internal error")
				return
			}
			if exists {
				fail(w, http.StatusForbidden, "document outside service scope")
				return
			}
		}
		fail(w, http.StatusNotFound, "document not found")
		return
	}
	if err != nil {
		log.Printf("read document failed request_id=%s: %v", r.Header.Get("X-Request-ID"), err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	a.audit(r.Context(), p, "document_read", "document", id, "success", r, nil)
	writeJSON(w, http.StatusOK, map[string]any{"document_id": id, "application_id": appID, "document_number": number, "document_title": title, "mime_type": mimeType, "content_base64": base64.StdEncoding.EncodeToString(content), "content_hash_sha256": hash, "status": status, "issued_at": issued})
}

