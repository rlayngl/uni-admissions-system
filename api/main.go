func main() {
	ctx := context.Background()
	pepper := []byte(os.Getenv("PASSWORD_PEPPER"))
	if len(pepper) < 32 {
		log.Fatal("PASSWORD_PEPPER must contain at least 32 bytes")
	}
	if strings.TrimSpace(os.Getenv("DATABASE_URL")) == "" {
		log.Fatal("DATABASE_URL is required")
	}
	db, err := pgxpool.New(ctx, os.Getenv("DATABASE_URL"))
	if err != nil {
		log.Fatalf("database configuration failed: %v", err)
	}
	defer db.Close()
	connected := false
	for i := 0; i < 30; i++ {
		if db.Ping(ctx) == nil {
			connected = true
			break
		}
		time.Sleep(time.Second)
	}
	if !connected {
		log.Fatal("database unavailable after retries")
	}
	redisPass := os.Getenv("REDIS_PASSWORD")
	rdb := redis.NewClient(&redis.Options{Addr: env("REDIS_ADDR", "redis:6379"), Password: redisPass, DialTimeout: 3 * time.Second, ReadTimeout: 3 * time.Second, WriteTimeout: 3 * time.Second})
	if err := rdb.Ping(ctx).Err(); err != nil {
		log.Fatalf("Redis is required for sessions and rate limiting: %v", err)
	}
	defer rdb.Close()
	dummyHash, err := hashPassword("not-a-real-account-password", pepper)
	if err != nil {
		log.Fatalf("dummy verifier generation failed: %v", err)
	}
	ttlSeconds, err := strconv.Atoi(env("SESSION_TTL_SECONDS", "1800"))
	if err != nil || ttlSeconds < 60 || ttlSeconds > 86400 {
		log.Fatal("SESSION_TTL_SECONDS must be between 60 and 86400")
	}
	a := &App{db: db, rdb: rdb, pepper: pepper, dummyHash: dummyHash, ttl: time.Duration(ttlSeconds) * time.Second}
	a.seed(ctx)
	mux := http.NewServeMux()
	mux.HandleFunc("POST /api/v1/auth/login", a.login)
	mux.HandleFunc("POST /api/v1/auth/recovery", a.resetRequest)
	mux.HandleFunc("POST /api/v1/auth/recovery/confirm", a.resetConfirm)
	mux.HandleFunc("POST /api/v1/auth/logout", a.auth(a.logout))
	mux.HandleFunc("POST /api/v1/applications", a.auth(a.createApplication))
	mux.HandleFunc("GET /api/v1/applications", a.auth(a.listApplications))
	mux.HandleFunc("GET /api/v1/applications/{application_id}", a.auth(a.application))
	mux.HandleFunc("PATCH /api/v1/applications/{application_id}/status", a.admin(a.changeStatus))
	mux.HandleFunc("POST /api/v1/applications/{application_id}/issue", a.admin(a.issue))
	mux.HandleFunc("GET /api/v1/documents/{document_id}", a.auth(a.getDocument))
	mux.HandleFunc("GET /api/v1/audit/events", a.auth(a.auditList))
	mux.HandleFunc("POST /api/v1/applications/{application_id}/ai/completeness-check", a.auth(a.aiNotImplemented))
	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, r *http.Request) {
		if db.Ping(r.Context()) != nil || rdb.Ping(r.Context()).Err() != nil {
			fail(w, http.StatusServiceUnavailable, "dependency unavailable")
			return
		}
		writeJSON(w, http.StatusOK, map[string]string{"status": "ok"})
	})
	srv := &http.Server{Addr: env("API_ADDR", ":8080"), Handler: withRequestID(withSecurityHeaders(mux)), ReadHeaderTimeout: 5 * time.Second, ReadTimeout: 15 * time.Second, WriteTimeout: 30 * time.Second, IdleTimeout: 60 * time.Second}
	log.Printf("API listening on %s", srv.Addr)
	if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
		log.Fatalf("HTTP server failed: %v", err)
	}
}

func (a *App) seed(ctx context.Context) {
	accounts := []struct{ id, uid, name, email, unit, role, password string }{
		{"11111111-1111-4111-8111-111111111111", "student01", "Алексей Пользователь", "student01@example.local", "STUDENT", "USER", "Student-Demo-2026!"},
		{"22222222-2222-4222-8222-222222222222", "student02", "Мария Пользователь", "student02@example.local", "STUDENT", "USER", "Student-Demo-2026!"},
		{"33333333-3333-4333-8333-333333333333", "staff01", "Ирина Сотрудник", "staff01@example.local", "STUDENT", "ADMIN", "Staff-Demo-2026!"},
		{"44444444-4444-4444-8444-444444444444", "tech01", "Технический специалист", "tech01@example.local", "", "TECH", "Tech-Demo-2026!"},
	}
	for _, u := range accounts {
		var existingID string
		err := a.db.QueryRow(ctx, `SELECT user_id::text FROM users WHERE university_id=$1`, u.uid).Scan(&existingID)
		if err != nil && !errors.Is(err, pgx.ErrNoRows) {
			log.Printf("seed lookup user %s failed: %v", u.uid, err)
			continue
		}
		if errors.Is(err, pgx.ErrNoRows) {
			verifier, hashErr := hashPassword(u.password, a.pepper)
			if hashErr != nil {
				log.Printf("seed password hash failed: %v", hashErr)
				continue
			}
			_, err = a.db.Exec(ctx, `INSERT INTO users(user_id,university_id,full_name,email,service_unit_code,password_hash) VALUES($1::uuid,$2,$3,$4,NULLIF($5,''),$6)`, u.id, u.uid, u.name, u.email, u.unit, verifier)
			if err != nil {
				log.Printf("seed user %s failed: %v", u.uid, err)
				continue
			}
			existingID = u.id
		}
		if _, err = a.db.Exec(ctx, `INSERT INTO user_roles(user_id,role_id) SELECT $1::uuid,role_id FROM roles WHERE code=$2 ON CONFLICT DO NOTHING`, existingID, u.role); err != nil {
			log.Printf("seed role %s failed: %v", u.uid, err)
		}
	}
	for _, x := range []struct{ id, owner, typ, comment string }{
		{"aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa", accounts[0].id, "STUDY_CERT", "Demo application for student01"},
		{"bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb", accounts[1].id, "GRADE_CERT", "Demo application for student02"},
	} {
		_, err := a.db.Exec(ctx, `INSERT INTO applications(application_id,owner_user_id,service_unit_code,document_type_id,status,comment)
			SELECT $1::uuid,$2::uuid,'STUDENT',document_type_id,'submitted',$4 FROM document_types WHERE code=$3 ON CONFLICT(application_id) DO NOTHING`, x.id, x.owner, x.typ, x.comment)
		if err != nil {
			log.Printf("seed application failed: %v", err)
		}
	}
}

