func (a *App) resetRequest(w http.ResponseWriter, r *http.Request) {
	if !a.rateLimit(w, r, "recovery-ip:"+clientIP(r), 5, time.Minute) {
		return
	}
	var in struct {
		UniversityID string `json:"university_id"`
	}
	if decode(w, r, &in) != nil || strings.TrimSpace(in.UniversityID) == "" {
		fail(w, http.StatusBadRequest, "invalid request")
		return
	}
	// Same response for present and absent accounts prevents account enumeration.
	var userID, email string
	err := a.db.QueryRow(r.Context(), `SELECT user_id::text,email FROM users WHERE university_id=$1 AND is_active=TRUE`, strings.TrimSpace(in.UniversityID)).Scan(&userID, &email)
	if err == nil {
		code, genErr := randomHex(24)
		if genErr != nil {
			fail(w, http.StatusInternalServerError, "internal error")
			return
		}
		sum := sha256.Sum256([]byte(code))
		tokenHash := hex.EncodeToString(sum[:])
		tx, txErr := a.db.Begin(r.Context())
		if txErr == nil {
			_, txErr = tx.Exec(r.Context(), `UPDATE password_reset_tokens SET used_at=now() WHERE user_id=$1::uuid AND used_at IS NULL`, userID)
		}
		if txErr == nil {
			_, txErr = tx.Exec(r.Context(), `INSERT INTO password_reset_tokens(token_hash,user_id,expires_at,used_at) VALUES($1,$2::uuid,now()+interval '20 minutes',NULL)`, tokenHash, userID)
		}
		if txErr == nil {
			txErr = tx.Commit(r.Context())
		} else if tx != nil {
			_ = tx.Rollback(r.Context())
		}
		if txErr != nil {
			log.Printf("recovery token transaction failed: %v", txErr)
			fail(w, http.StatusInternalServerError, "internal error")
			return
		}
		// Local-only mail stub required for this lab. Never enable reset-code
		// logging outside the isolated development environment.
		log.Printf("[LOCAL RESET MAIL STUB] recipient=%s user=%s code=%s expires=20m", email, userID, code)
	} else if !errors.Is(err, pgx.ErrNoRows) {
		log.Printf("recovery request query failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	writeJSON(w, http.StatusAccepted, map[string]string{"message": "If the account exists, recovery instructions have been sent."})
}

func (a *App) resetConfirm(w http.ResponseWriter, r *http.Request) {
	if !a.rateLimit(w, r, "recovery-confirm-ip:"+clientIP(r), 10, time.Minute) {
		return
	}
	var in struct {
		Code        string `json:"code"`
		NewPassword string `json:"new_password"`
	}
	if decode(w, r, &in) != nil || strings.TrimSpace(in.Code) == "" || len(in.NewPassword) < 12 || len(in.NewPassword) > 1024 {
		fail(w, http.StatusBadRequest, "invalid request")
		return
	}
	sum := sha256.Sum256([]byte(strings.TrimSpace(in.Code)))
	tokenHash := hex.EncodeToString(sum[:])
	tx, err := a.db.Begin(r.Context())
	if err != nil {
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	defer tx.Rollback(r.Context())
	var userID string
	err = tx.QueryRow(r.Context(), `SELECT user_id::text FROM password_reset_tokens WHERE token_hash=$1 AND used_at IS NULL AND expires_at>now() FOR UPDATE`, tokenHash).Scan(&userID)
	if errors.Is(err, pgx.ErrNoRows) {
		fail(w, http.StatusBadRequest, "invalid or expired reset code")
		return
	}
	if err != nil {
		log.Printf("password reset token lookup failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	passwordHash, err := hashPassword(in.NewPassword, a.pepper)
	if err != nil {
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	if _, err = tx.Exec(r.Context(), `UPDATE users SET password_hash=$1,password_pepper_version=1 WHERE user_id=$2::uuid`, passwordHash, userID); err == nil {
		_, err = tx.Exec(r.Context(), `UPDATE password_reset_tokens SET used_at=now() WHERE token_hash=$1`, tokenHash)
	}
	if err != nil {
		log.Printf("password reset database update failed: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	// Fail closed: revoke active sessions before committing the password reset.
	// If Redis is unavailable, the transaction rolls back and the code remains usable.
	tokens, redisErr := a.rdb.SMembers(r.Context(), "sessions:user:"+userID).Result()
	if redisErr != nil {
		log.Printf("password reset session lookup failed: %v", redisErr)
		fail(w, http.StatusServiceUnavailable, "session service unavailable")
		return
	}
	revokeKeys := make([]string, 0, len(tokens)+1)
	for _, token := range tokens {
		revokeKeys = append(revokeKeys, "session:"+token)
	}
	revokeKeys = append(revokeKeys, "sessions:user:"+userID)
	if err := a.rdb.Del(r.Context(), revokeKeys...).Err(); err != nil {
		log.Printf("password reset session revocation failed: %v", err)
		fail(w, http.StatusServiceUnavailable, "session service unavailable")
		return
	}
	if err := tx.Commit(r.Context()); err != nil {
		log.Printf("password reset commit failed after safe session revocation: %v", err)
		fail(w, http.StatusInternalServerError, "internal error")
		return
	}
	writeJSON(w, http.StatusOK, map[string]string{"status": "password_changed"})
}

