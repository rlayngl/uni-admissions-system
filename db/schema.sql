-- PostgreSQL DDL. Выполняется на чистой базе без расширений.

CREATE TABLE roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL
);

CREATE TABLE users (
    user_id UUID PRIMARY KEY,
    university_id VARCHAR(32) NOT NULL UNIQUE,
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(320) NOT NULL UNIQUE,
    phone VARCHAR(32),
    service_unit_code VARCHAR(32),
    password_hash TEXT NOT NULL,
    password_pepper_version SMALLINT NOT NULL DEFAULT 1 CHECK (password_pepper_version > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_roles (
    user_id UUID NOT NULL REFERENCES users(user_id),
    role_id SMALLINT NOT NULL REFERENCES roles(role_id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE document_types (
    document_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    description TEXT,
    requires_original BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE applications (
    application_id UUID PRIMARY KEY,
    owner_user_id UUID NOT NULL REFERENCES users(user_id),
    service_unit_code VARCHAR(32) NOT NULL,
    document_type_id SMALLINT NOT NULL REFERENCES document_types(document_type_id),
    status VARCHAR(24) NOT NULL DEFAULT 'submitted'
        CHECK (status IN ('submitted', 'in_review', 'approved', 'rejected', 'issued', 'cancelled')),
    comment TEXT CHECK (comment IS NULL OR char_length(comment) <= 2000),
    idempotency_key VARCHAR(128),
    idempotency_payload_hash VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_applications_owner_idempotency UNIQUE (owner_user_id, idempotency_key),
    CONSTRAINT ck_applications_idempotency_pair CHECK (
        (idempotency_key IS NULL AND idempotency_payload_hash IS NULL)
        OR (idempotency_key IS NOT NULL AND char_length(idempotency_key) BETWEEN 8 AND 128
            AND idempotency_payload_hash ~ '^[0-9a-f]{64}$')
    )
);

CREATE TABLE application_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id UUID NOT NULL REFERENCES applications(application_id),
    changed_by_user_id UUID NOT NULL REFERENCES users(user_id),
    old_status VARCHAR(24) NOT NULL,
    new_status VARCHAR(24) NOT NULL,
    reason TEXT CHECK (reason IS NULL OR char_length(reason) <= 2000),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_id UUID
);

CREATE TABLE documents (
    document_id UUID PRIMARY KEY,
    application_id UUID NOT NULL UNIQUE REFERENCES applications(application_id),
    owner_user_id UUID NOT NULL REFERENCES users(user_id),
    document_number VARCHAR(64) NOT NULL UNIQUE,
    document_title VARCHAR(240) NOT NULL,
    mime_type VARCHAR(100) NOT NULL DEFAULT 'application/pdf',
    document_content BYTEA NOT NULL,
    content_hash_sha256 CHAR(64) NOT NULL CHECK (content_hash_sha256 ~ '^[0-9a-fA-F]{64}$'),
    issued_by_user_id UUID NOT NULL REFERENCES users(user_id),
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(16) NOT NULL DEFAULT 'issued' CHECK (status IN ('issued', 'revoked')),
    revoked_at TIMESTAMPTZ,
    CHECK ((status = 'issued' AND revoked_at IS NULL) OR (status = 'revoked' AND revoked_at IS NOT NULL))
);

CREATE TABLE document_issue_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id UUID NOT NULL REFERENCES documents(document_id),
    application_id UUID NOT NULL REFERENCES applications(application_id),
    actor_user_id UUID NOT NULL REFERENCES users(user_id),
    document_hash_sha256 CHAR(64) NOT NULL CHECK (document_hash_sha256 ~ '^[0-9a-fA-F]{64}$'),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_id UUID NOT NULL
);

CREATE TABLE audit_events (
    audit_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id UUID REFERENCES users(user_id),
    event_type VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_ref VARCHAR(80),
    outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('success', 'denied', 'error')),
    event_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_id UUID,
    source_ip INET,
    details JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE ai_checks (
    ai_check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id UUID NOT NULL REFERENCES users(user_id),
    application_id UUID NOT NULL REFERENCES applications(application_id),
    provider VARCHAR(120) NOT NULL,
    model_name VARCHAR(160) NOT NULL,
    input_fingerprint CHAR(64) NOT NULL CHECK (input_fingerprint ~ '^[0-9a-fA-F]{64}$'),
    result JSONB NOT NULL,
    latency_ms INTEGER CHECK (latency_ms IS NULL OR latency_ms >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id UUID NOT NULL REFERENCES applications(application_id),
    recipient_user_id UUID NOT NULL REFERENCES users(user_id),
    recipient_address VARCHAR(320) NOT NULL,
    notification_type VARCHAR(32) NOT NULL CHECK (notification_type IN ('status_changed', 'document_ready')),
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMPTZ,
    last_error TEXT
);

CREATE TABLE outbox_events (
    outbox_event_id UUID PRIMARY KEY,
    aggregate_type VARCHAR(64) NOT NULL,
    aggregate_id UUID NOT NULL,
    event_type VARCHAR(96) NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error TEXT
);

-- Delivery de-duplication key: one notification record per outbox event.
ALTER TABLE notifications
    ADD COLUMN source_outbox_event_id UUID UNIQUE REFERENCES outbox_events(outbox_event_id);

-- Индексы для проверок полномочий и фильтрации.
CREATE INDEX idx_applications_owner_status_created
    ON applications(owner_user_id, status, created_at DESC);
CREATE INDEX idx_applications_unit_status_created
    ON applications(service_unit_code, status, created_at DESC);
CREATE INDEX idx_applications_type_created
    ON applications(document_type_id, created_at DESC);
CREATE INDEX idx_status_history_application_time
    ON application_status_history(application_id, changed_at DESC);
CREATE INDEX idx_documents_owner_issued
    ON documents(owner_user_id, issued_at DESC);
CREATE INDEX idx_documents_application
    ON documents(application_id);
CREATE INDEX idx_audit_actor_time
    ON audit_events(actor_user_id, event_time DESC);
CREATE INDEX idx_audit_entity_time
    ON audit_events(entity_type, entity_ref, event_time DESC);
CREATE INDEX idx_ai_checks_owner_application
    ON ai_checks(owner_user_id, application_id, created_at DESC);
CREATE INDEX idx_notifications_status_created
    ON notifications(status, created_at);
CREATE INDEX idx_outbox_unpublished
    ON outbox_events(created_at)
    WHERE published_at IS NULL;

-- Вспомогательная функция защиты выданного документа от изменения содержания/реквизитов.
CREATE OR REPLACE FUNCTION prevent_issued_document_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'issued' THEN
        IF NEW.application_id IS DISTINCT FROM OLD.application_id
           OR NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id
           OR NEW.document_number IS DISTINCT FROM OLD.document_number
           OR NEW.document_title IS DISTINCT FROM OLD.document_title
           OR NEW.mime_type IS DISTINCT FROM OLD.mime_type
           OR NEW.document_content IS DISTINCT FROM OLD.document_content
           OR NEW.content_hash_sha256 IS DISTINCT FROM OLD.content_hash_sha256
           OR NEW.issued_by_user_id IS DISTINCT FROM OLD.issued_by_user_id
           OR NEW.issued_at IS DISTINCT FROM OLD.issued_at
        THEN
            RAISE EXCEPTION 'Issued document content or essential attributes are immutable';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_documents_immutability
BEFORE UPDATE ON documents
FOR EACH ROW
EXECUTE FUNCTION prevent_issued_document_mutation();

-- Выданный документ нельзя удалить обычной операцией приложения.
CREATE OR REPLACE FUNCTION prevent_document_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Documents are not physically deleted';
END;
$$;

CREATE TRIGGER trg_documents_no_delete
BEFORE DELETE ON documents
FOR EACH ROW
EXECUTE FUNCTION prevent_document_delete();

-- История выдачи и аудит являются append-only.
CREATE OR REPLACE FUNCTION prevent_append_only_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Append-only record cannot be changed or deleted';
END;
$$;

CREATE TRIGGER trg_issue_events_no_update_delete
BEFORE UPDATE OR DELETE ON document_issue_events
FOR EACH ROW
EXECUTE FUNCTION prevent_append_only_mutation();

CREATE TRIGGER trg_audit_events_no_update_delete
BEFORE UPDATE OR DELETE ON audit_events
FOR EACH ROW
EXECUTE FUNCTION prevent_append_only_mutation();

